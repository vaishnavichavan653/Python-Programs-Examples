import numpy as np

a = np.array([[10, 20], [30, 40]])
b = np.array([[2, 4], [5, 8]])

print("Array A:")
print(a)

print("Array B:")
print(b)

print("Addition:")
print(a + b)

print("Subtraction:")
print(a - b)

print("Multiplication:")
print(a * b)

print("Division:")
print(a / b)

print("Transpose of A:")
print(a.T)

print("Exponential of A:")
print(np.exp(a))